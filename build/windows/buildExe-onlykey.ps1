################################################################################
# File:    build/windows/buildExe-onlykey.ps1
# Purpose: Build a single-file windowed Windows .exe of the OnlyKey-enabled
#          BusKill fork, using PyInstaller against a Python 3.10 venv with
#          Kivy 2.3.1 + pystray.
#
#          This is a modern rewrite of the upstream buildExe.ps1, which is
#          hardwired to Python 3.7 / Kivy 1.11 and is left in place for
#          reference only.
#
# Usage:   From the repo root, with the venv already created:
#            .\build\windows\buildExe-onlykey.ps1
#
#          To create the venv from scratch first:
#            python -m venv venv
#            .\venv\Scripts\python.exe -m pip install `
#              pywin32 certifi python-gnupg `
#              "kivy[base]" pystray Pillow pyinstaller
################################################################################

# NOTE on ErrorActionPreference: PyInstaller writes its INFO/WARNING progress
# lines to stderr. Under PowerShell 5.1 with ErrorActionPreference='Stop',
# each stderr line gets wrapped in a NativeCommandError and aborts the script
# even when PyInstaller exited cleanly. So we use 'Continue' here and check
# $LASTEXITCODE explicitly after each native-exe call.
$ErrorActionPreference = 'Continue'

# Resolve repo root (this script lives at build/windows/buildExe-onlykey.ps1)
$repoRoot = (Resolve-Path "$PSScriptRoot\..\..").Path
Set-Location $repoRoot

Write-Output "Repo root: $repoRoot"

# Locate the venv
$venvPython = Join-Path $repoRoot 'venv\Scripts\python.exe'
if (-not (Test-Path $venvPython)) {
    Write-Error "venv not found at $venvPython. See the Usage comment above."
    exit 1
}

# Reproducible build environment
$env:PYTHONHASHSEED = '0'
$env:SOURCE_DATE_EPOCH = (git log -1 --pretty=%ct).Trim()

# Generate src\buskill_version.py with current git info so the app's
# About / Debug log show useful identifiers.
$gitSha    = (git rev-parse HEAD).Trim()
$gitRef    = (git symbolic-ref HEAD 2>$null)
if (-not $gitRef) { $gitRef = 'detached' } else { $gitRef = $gitRef.Trim() }
$verBranch = $gitRef.Split('/')[-1]
$shortSha  = $gitSha.Substring(0, 8)
$version   = "$verBranch-$shortSha-onlykey"

$verContent = @"
# -*- mode: python ; coding: utf-8 -*-
# Generated by build/windows/buildExe-onlykey.ps1; do not edit by hand.
BUSKILL_VERSION = {
 'VERSION': '$version',
 'GITHUB_REF': '$gitRef',
 'GITHUB_SHA': '$gitSha',
 'SOURCE_DATE_EPOCH': '$($env:SOURCE_DATE_EPOCH)',
}
"@
Set-Content -Path 'src\buskill_version.py' -Value $verContent -Encoding utf8
Write-Output "Wrote src\buskill_version.py with version: $version"

# Clean previous build artifacts so we always get a fresh result
# (Do NOT delete buskill.spec — that's checked-in source.)
foreach ($d in @('build\windows\build', 'build\windows\dist')) {
    if (Test-Path $d) {
        Write-Output "Cleaning $d"
        Remove-Item -Recurse -Force $d
    }
}

Write-Output ''
Write-Output 'Running PyInstaller (this can take a few minutes)...'
Write-Output ''

# We use a hand-written .spec file (build\windows\buskill.spec) instead of
# command-line args. This is the Kivy-recommended packaging path because it
# wires in kivy.tools.packaging.pyinstaller_hooks and kivy_deps explicitly,
# which avoids issues like PyInstaller's --collect-all choking on Kivy's
# namespace-package __path__.
& $venvPython -m PyInstaller `
    --noconfirm `
    --workpath "build\windows\build" `
    --distpath "build\windows\dist" `
    "build\windows\buskill.spec"

if ($LASTEXITCODE -ne 0) {
    Write-Error "PyInstaller failed with exit code $LASTEXITCODE"
    exit $LASTEXITCODE
}

$exePath = Join-Path $repoRoot 'build\windows\dist\buskill.exe'
if (Test-Path $exePath) {
    $size = (Get-Item $exePath).Length / 1MB
    Write-Output ''
    Write-Output '===================================='
    Write-Output "Build complete: $exePath"
    Write-Output ("Size: {0:N1} MB" -f $size)
    Write-Output '===================================='
} else {
    Write-Error "Expected exe not found at $exePath"
    exit 1
}
